function Deploy-File {
    param([string]$TargetPath, [string]$Base64Content, [string]$Label)
    Write-Host ('[PATCH] ' + $Label)
    if (Test-Path $TargetPath) {
        $backupName = Split-Path $TargetPath -Leaf
        $backupPath = Join-Path $DeployRoot ('backup_phase32_arp_' + (Get-Date -Format 'yyyyMMdd_HHmmss'))
        if (-not (Test-Path $backupPath)) { New-Item -ItemType Directory -Force -Path $backupPath | Out-Null }
        Copy-Item $TargetPath (Join-Path $backupPath $backupName) -Force
        Write-Host ('  [BACKUP] ' + $TargetPath)
    } else {
        $parentDir = Split-Path $TargetPath -Parent
        if ($parentDir -and -not (Test-Path $parentDir)) { New-Item -ItemType Directory -Force -Path $parentDir | Out-Null }
    }
    $bytes = [System.Convert]::FromBase64String($Base64Content)
    [System.IO.File]::WriteAllBytes($TargetPath, $bytes)
    Write-Host ('  [WRITE] ' + $TargetPath + ' (' + $bytes.Length + ' bytes)')
}

