# Architecture (Manual Section 23):
#   TypeScript -> Policy Definition -> Compiler -> Policy IR -> Signer -> Rust
#
# TypeScript does: authoring, editing, simulation
# Rust does: validation, security, enforcement
#
# This module defines:
#   1. PolicyIR: stable intermediate representation (magic POL1, version 1)
#   2. PolicyRuleDef: rule definition (conditions -> action)
#   3. PolicyCompiler: compiles rules into PolicyIR with hash + signature
#   4. PolicySimulator: what-if testing without enforcement
