$ErrorActionPreference = 'Continue'
$DeployRoot = $PSScriptRoot
if (-not $DeployRoot) { $DeployRoot = (Get-Location).Path }
$BackupDir = Join-Path $DeployRoot ('backup_phase27_' + (Get-Date -Format 'yyyyMMdd_HHmmss'))
New-Item -ItemType Directory -Force -Path $BackupDir | Out-Null
function Deploy-File {
    param([string]$TargetPath, [string]$Base64Content, [string]$Label)
    Write-Host ('[DEPLOY] ' + $Label)
    if (Test-Path $TargetPath) {
        $backupName = Split-Path $TargetPath -Leaf
        $backupPath = Join-Path $BackupDir $backupName
        Copy-Item $TargetPath $backupPath -Force
        Write-Host ('  [BACKUP] ' + $TargetPath + ' -> ' + $backupPath)
    } else {
        $parentDir = Split-Path $TargetPath -Parent
        if (-not (Test-Path $parentDir)) {
            New-Item -ItemType Directory -Force -Path $parentDir | Out-Null
            Write-Host ('  [MKDIR] ' + $parentDir)
        }
    }
    $bytes = [System.Convert]::FromBase64String($Base64Content)
    [System.IO.File]::WriteAllBytes($TargetPath, $bytes)
    Write-Host ('  [WRITE] ' + $TargetPath + ' (' + $bytes.Length + ' bytes)')
}
