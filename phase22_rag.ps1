# ============================================================
# AEGIS NIDS - Phase 22: RAG (Retrieval Augmented Generation)
# ============================================================
# RAG enriches verdict context with retrieved intelligence.
#
# Architecture (Manual Section 21):
#   Canonical Event -> Threat Intel -> Detection -> Correlation -> RAG
#   RAG returns: context, references, confidence, provenance
#
# Critical rules:
#   - RAG must NOT block (fail-soft: returns empty context if unavailable)
#   - System works when RAG unavailable
#   - RAG enriches, it does not authorize
#
# Knowledge base: 8 builtin entries
#   - malware_signature (C2 IPs)
#   - attack_pattern (rule IDs -> MITRE ATT&CK)
#   - threat_actor (botnet nodes)
#   - false_positive_indicator (private IPs)
#   - mitigation (brute force -> rate limit)
#   - contextual_benign (unknown IPs)
#   - vulnerability (CVE references)
#
# RagContext: available, match_count, context_summary, references[8],
#   confidence, primary_category, event_id
#
# Fail-soft: setAvailable(false) disables RAG, query returns empty context
# ============================================================
$ErrorActionPreference = 'Continue'
$DeployRoot = $PSScriptRoot
if (-not $DeployRoot) { $DeployRoot = (Get-Location).Path }
$BackupDir = Join-Path $DeployRoot ('backup_phase22_' + (Get-Date -Format 'yyyyMMdd_HHmmss'))
New-Item -ItemType Directory -Force -Path $BackupDir | Out-Null
function Deploy-File {
    param([string]$TargetPath, [string]$Base64Content, [string]$Label)
    Write-Host ('[DEPLOY] ' + $Label)
    if (Test-Path $TargetPath) {
        $backupName = Split-Path $TargetPath -Leaf
        $backupPath = Join-Path $BackupDir $backupName
        Copy-Item $TargetPath $backupPath -Force
        Write-Host ('  [BACKUP] ' + $TargetPath + ' -> ' + $backupPath)
    } else {
        $parentDir = Split-Path $TargetPath -Parent
        if (-not (Test-Path $parentDir)) {
            New-Item -ItemType Directory -Force -Path $parentDir | Out-Null
            Write-Host ('  [MKDIR] ' + $parentDir)
        }
    }
    $bytes = [System.Convert]::FromBase64String($Base64Content)
    [System.IO.File]::WriteAllBytes($TargetPath, $bytes)
    Write-Host ('  [WRITE] ' + $TargetPath + ' (' + $bytes.Length + ' bytes)')
}
